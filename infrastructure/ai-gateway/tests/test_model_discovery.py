def local_python_image():
    """Inspect/probe local images only, never output image config or pull anything."""
    selected = os.environ.get("GATEWAY_MODEL_PYTHON_IMAGE")
    candidates = [selected] if selected else sorted(set(docker("images", "--quiet", "--no-trunc").split()))
    for candidate in candidates:
        try:
            identifier = docker("image", "inspect", "--format={{.Id}}", candidate).strip()
            if not re.fullmatch(r"sha256:[a-f0-9]{64}", identifier):
                continue
            # No namespace sharing or fixture secrets during interpreter discovery.
            # Override entrypoint, user and networking; discard all captured output.
            docker("run", "--rm", "--pull=never", "--network=none", "--read-only",
                   "--cap-drop=ALL", "--security-opt=no-new-privileges:true", "--log-driver=none",
                   "--user=65534:65534", "--memory=128m", "--pids-limit=32", "--entrypoint=python3",
                   identifier, "-I", "-S", "-B", "-c",
                   "import http.client, http.server, json, re, sys, threading; assert sys.version_info >= (3, 11)")
        except RuntimeError:
            continue
        return identifier
    raise RuntimeError("No local Python 3.11+ image is usable; select GATEWAY_MODEL_PYTHON_IMAGE (no images pulled)")


@unittest.skipUnless(os.environ.get("GATEWAY_MODEL_CONTAINER_TESTS") == "1",
                     "Opt-in isolated Docker model-discovery proof")
class ModelDiscoveryTests(unittest.TestCase):
    def api(self, path, method="GET", payload=None):
        code, body, _ = request(self.backend, path, method, self.admin, payload)
        self.assertIn(code, (200, 201), "Management API status")
        return json_object(body)

    def virtual_key(self, name, grants=()):
        # Empty grants deliberately inherit deny-by-default; never allow-all.
        result = self.api("/api/governance/virtual-keys", "POST", {
            "name": name, "provider_configs": [
                {"provider": provider, "allowed_models": list(models),
                 "key_ids": [self.provider_keys[provider]]}
                for provider, models in grants
            ],
        }).get("virtual_key", {})
        self.assertTrue(isinstance(result, dict), "VK response shape")
        value, identifier = result.get("value"), result.get("id")
        self.assertTrue(isinstance(value, str) and bool(re.fullmatch(r"sk-bf-[A-Za-z0-9_-]+", value)),
                        "Generated VK must match the edge token format")
        self.assertTrue(isinstance(identifier, str) and bool(re.fullmatch(r"[A-Za-z0-9_-]+", identifier)),
                        "Generated VK must have a safe resource ID")
        self.private_values.append(value)
        stored = self.api("/api/governance/virtual-keys/" + identifier).get("virtual_key", {})
        self.assertTrue(stored.get("is_active") is True, "Stored VK must be active")
        self.assertTrue(stored.get("allow_all_providers") is False, "Stored VK must not allow all providers")
        configs = stored.get("provider_configs") or []
        self.assertEqual(len(configs), len(grants))
        self.assertTrue({config.get("provider") for config in configs} == {provider for provider, _ in grants},
                        "Stored provider identities")
        for provider, models in grants:
            config = next(config for config in configs if config.get("provider") == provider)
            self.assertTrue(set(config.get("allowed_models") or []) == set(models), "Stored model grant")
            self.assertTrue(config.get("allow_all_keys") is False, "Stored provider key grant")
            self.assertEqual(len(config.get("keys") or []), 1, "Stored grant must bind one provider key")
            key = config["keys"][0]
            self.assertTrue(key.get("key_id", key.get("id")) == self.provider_keys[provider],
                            "Stored provider key identity")
        return identifier, {"Authorization": "Bearer " + value}

    def revoke(self, identifier):
        self.api("/api/governance/virtual-keys/" + identifier, "PUT", {"is_active": False})
        stored = self.api("/api/governance/virtual-keys/" + identifier).get("virtual_key", {})
        self.assertTrue(stored.get("is_active") is False, "Stored VK must be revoked")

    def observe(self, label, port, headers, allowed, path):
        """Never let raw responses/errors become unittest assertion operands."""
        code, body, response_headers = request(port, path, headers=headers)
        counts = model_observation(code, body, response_headers, allowed,
                                   self.provider_keys, self.private_values)
        print(json.dumps({"case": label, **counts}, sort_keys=True), flush=True)
        self.assertEqual(counts["credential_hits"], 0, "Response must not echo credentials")
        self.assertEqual(counts["json_object"], 1, "Response must be a JSON object")
        self.assertEqual(counts["json_content_type"], 1, "Response must declare JSON")
        self.assertEqual(counts["encoded_body"], 0, "Identity transport must not return compressed bytes")
        return counts

    def assert_identities(self, counts, allowed):
        self.assertEqual(counts["models"], len(allowed), "Exact scoped model count")
        self.assertEqual(counts["malformed_rows"] + counts["duplicate_ids"], 0, "Unique string model IDs")
        self.assertEqual(counts["unexpected_models"] + counts["missing_models"], 0, "Exact scoped model identities")

    def raw_probe(self, label, headers, allowed=(), *, code=200, quirk):
        """Pinned backend characterization, NOT public-edge authorization success.

        Explicit exceptions: empty deployment returns 200 [] even for invalid or
        revoked keys; configured errors disclose provider diagnostics; successful
        VK data is scoped but key_statuses is not safe public response metadata.
        Keep these assertions independent of (and weaker ONLY here than) the edge.
        """
        with self.subTest(raw_backend=label):
            counts = self.observe("raw/" + label, self.backend, headers, allowed, "/v1/models")
            self.assertEqual(counts["status"], code, "Pinned raw-backend characterization status")
            self.assert_identities(counts, allowed)
            if code == 200:
                self.assertEqual(counts["data_array"], 1)
            if quirk == "empty-auth-bypass":
                self.assertEqual(counts["models"], 0, "Empty raw success is NOT evidence of authentication")
            elif quirk == "denial-metadata":
                self.assertGreater(counts["forbidden_metadata"], 0, "Pinned denial exposes provider metadata")
            elif quirk == "scoped-data-with-diagnostics":
                self.assertGreater(counts["key_status_fields"], 0, "Pinned scoped catalog includes key diagnostics")
            else:
                self.fail("Unknown raw-backend characterization")

    def edge_probe(self, label, headers, allowed=(), *, path="/v1/models", code=200):
        """Strict exact projection/error contract; raw-backend quirks never pass here."""
        with self.subTest(case=label):
            counts = self.observe("edge/" + label, self.edge, headers, allowed, path)
            self.assertEqual(counts["forbidden_metadata"], 0, "Response must not disclose another scope")
            self.assertEqual(counts["key_status_fields"], 0, "Key diagnostics must be stripped entirely")
            self.assertEqual(counts["status"], code, "Exact guarded-edge status")
            self.assert_identities(counts, allowed)
            if code == 200:
                self.assertGreater(len(allowed), 0, "Empty catalogs must never be an edge success")
                self.assertEqual(counts["exact_projection"], 1, "Only the exact public catalog may be returned")
                self.assertEqual(counts["error_fields"], 0, "No backend errors may survive projection")
            else:
                self.assertEqual(counts["exact_error"], 1, "Only the exact static guard error may be returned")


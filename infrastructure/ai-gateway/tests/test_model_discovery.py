    def test_empty_success_is_distinct_from_an_error(self):
        empty = model_observation(200, b'{"data": []}', [], (), {}, ())
        denied = model_observation(401, b'{"error": {"message": "denied"}}', [], (), {}, ())
        self.assertEqual((empty["models"], empty["error_fields"], empty["data_array"]), (0, 0, 1))
        self.assertEqual((denied["models"], denied["error_fields"], denied["data_array"]), (0, 1, 0))

